EXTRA = ["a31_in_K", "b31_in_K", "ord_a31_mod_K", "ord_b31_mod_K", "index_K_parity",
         "ord_delta0_mod_K", "has_half_near_coincidence",
         "a_third_minus_a_coin_in_K", "b_third_minus_b_coin_in_K"]


def extra_features(recs: list[dict]) -> dict:
    """6.4 -- cheap features on the odd-ord(d), non-obstructed region only."""
    from .features import coincident_pair
    region = [r for r in recs if not r["ord_d_even"] and not r["theorem1_obstructed"]
              and r["status_resolved"] in ("SAT", "UNSAT")]
    print(f"\n6.4  extra features on the odd-ord(d), non-obstructed region: "
          f"{len(region)} decided instances")
    for r in region:
        code = build_code(r)
        N = r["N"]
        g = gcd(r["d"], N) or N          # [Z_N : K] with K = <d>
        A = [a[0] for a in code.A]
        B = [b[0] for b in code.B]
        cp = coincident_pair(code)
        delta0, (s, t), (s2, t2) = cp
        third_s = ({0, 1, 2} - {s, s2}).pop()
        third_t = ({0, 1, 2} - {t, t2}).pop()
        a31 = (A[2] - A[0]) % N
        b31 = (B[2] - B[0]) % N
        r["index_K"] = g
        r["a31_in_K"] = (a31 % g == 0)
        r["b31_in_K"] = (b31 % g == 0)
        r["ord_a31_mod_K"] = g // gcd(g, a31 % g) if g else 1
        r["ord_b31_mod_K"] = g // gcd(g, b31 % g) if g else 1
        r["index_K_parity"] = g % 2
        d0 = delta0[0] % N
        r["ord_delta0_mod_K"] = g // gcd(g, d0 % g) if g else 1
        ac = (A[third_s] - A[s]) % N
        bc = (B[third_t] - B[t]) % N
        r["a_third_minus_a_coin_in_K"] = (ac % g == 0)
        r["b_third_minus_b_coin_in_K"] = (bc % g == 0)
        half = None
        if N % 2 == 0:
            sums = [((A[x] + B[y]) % N, (x, y)) for x in range(3) for y in range(3)]
            half = any((u - v) % N == N // 2
                       for u, _ in sums for v, _ in sums)
        r["has_half_near_coincidence"] = half if half is not None else ""
    if not region:
        return dict(n=0, note="region empty")

    print(f"     {'feature':30} {'values':>7} {'exact':>6} {'max cell':>9} {'singleton':>10}")
    findings = []
    for f in EXTRA:
        sep = separates(region, (f,))
        usable = sep["separates"] and sep["max_cell"] >= 5 and sep["frac_singleton"] < 0.5
        print(f"     {f:30} {sep['n_values']:7d} {str(sep['separates']):>6} "
              f"{sep['max_cell']:9d} {100*sep['frac_singleton']:9.0f}%"
              + ("   <-- usable separation" if usable else ""))
        findings.append(dict(sep, usable=usable))
    import itertools as _it
    pair_hits = []
    for a, b in _it.combinations(EXTRA, 2):
        sep = separates(region, (a, b))
        if sep["separates"] and sep["max_cell"] >= 5 and sep["frac_singleton"] < 0.5:
            pair_hits.append(sep)
    print(f"     feature pairs with a usable exact separation: {len(pair_hits)}"
          + (f" -> {[s['keys'] for s in pair_hits]}" if pair_hits else ""))
    usable_any = [f for f in findings if f["usable"]] + pair_hits
    print("     => " + ("NO usable exact separation on this region."
                        if not usable_any else
                        f"usable exact separations: "
                        f"{[' x '.join(s['keys']) for s in usable_any]}"))
    return dict(n=len(region), single=findings, pairs=pair_hits,
                usable=[s["keys"] for s in usable_any])


