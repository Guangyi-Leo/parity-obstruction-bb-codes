def _core_one(job):
    """One properness-level unsat core, with a hard per-instance time limit."""
    import time as _t

    from pysat.solvers import Cadical195

    from .encode import encode
    rec, limit = job
    t0 = _t.time()
    code = build_code(rec)
    enc = encode(code, DEPTH)
    sel0 = enc.nvars
    clauses = [list(c) for c in enc.clauses]
    sels = []
    for i, (a, b) in enumerate(enc.properness_ranges):
        s = sel0 + 1 + i
        sels.append(s)
        for j in range(a, b):
            clauses[j] = clauses[j] + [-s]
    with Cadical195(bootstrap_with=clauses) as solver:
        if solver.solve(assumptions=sels):
            return dict(instance=rec["instance"], status="SAT_UNEXPECTED")
        core = list(solver.get_core() or sels)
        # deletion-based minimisation inside the remaining budget
        minimal = True
        changed = True
        while changed and _t.time() - t0 < limit:
            changed = False
            for s in list(core):
                if _t.time() - t0 >= limit:
                    minimal = False
                    break
                trial = [x for x in core if x != s]
                if not solver.solve(assumptions=trial):
                    core = list(solver.get_core() or trial)
                    changed = True
            else:
                continue
            break
        else:
            if _t.time() - t0 >= limit:
                minimal = False
    idx = [sels.index(s) for s in core]
    ops = [code.overlap_pairs[i] for i in idx]
    N = rec["N"]
    g = gcd(rec["d"], N) or N
    checks = [op.gx for op in ops]
    coset = Counter(c % g for c in checks)
    labels = set()
    for op in ops:
        for cid in op.corners:
            cr = code.corners[cid]
            labels.add(code.edges[cr.ex].lab1)
            labels.add(code.edges[cr.ez].lab1)
    return dict(instance=rec["instance"], N=N, status="UNSAT",
                core_size=len(core), n_pairs_total=len(code.overlap_pairs),
                certified_minimal=minimal,
                coincident_pair_in_core=any(len(op.corners) > 2 for op in ops),
                label3_edges_in_core=(3 in labels),
                labels_in_core=json.dumps(sorted(labels)),
                deltas_in_core=json.dumps(sorted({op.delta[0] for op in ops})),
                index_K=g,
                coset_histogram=json.dumps({str(k): v for k, v in sorted(coset.items())}),
                n_cosets_touched=len(coset),
                seconds=round(_t.time() - t0, 1))


def unsat_cores(recs: list[dict], max_inst: int = 16, per_limit: float = 60.0,
                workers: int = 8, total_cap: float = 1200.0) -> dict:
    """6.5 -- optional; bounded properness-level cores for unexplained UNSAT."""
    import time as _t
    from concurrent.futures import ProcessPoolExecutor, as_completed

    cand = sorted([r for r in recs
                   if r["status"] == "UNSAT" and not r["theorem1_obstructed"]],
                  key=lambda r: (r["N"], r["instance"]))[:max_inst]
    print(f"\n6.5  unsat cores: {len(cand)} unexplained UNSAT instances "
          f"(smallest N first), {per_limit:.0f}s each, {workers} workers, "
          f"{total_cap:.0f}s total cap")
    if not cand:
        return dict(n=0, skipped=True, reason="no unexplained UNSAT instances")
    rows, t0 = [], _t.time()
    with ProcessPoolExecutor(max_workers=workers) as ex:
        futs = {ex.submit(_core_one, (r, per_limit)): r for r in cand}
        for fut in as_completed(futs):
            if _t.time() - t0 > total_cap:
                print("     total cap reached; stopping")
                break
            try:
                rows.append(fut.result())
            except Exception as e:                       # noqa: BLE001
                rows.append(dict(instance=futs[fut]["instance"], status=f"ERROR {e}"))
    if len(rows) < 4 and len(cand) >= 4:
        print("     fewer than 4 cores returned; module treated as skipped")
    ok = [r for r in rows if r.get("status") == "UNSAT"]
    out = os.path.join(DATA, "c1_unsat_cores.csv")
    if ok:
        with open(out, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(ok[0].keys()))
            w.writeheader()
            w.writerows(sorted(ok, key=lambda r: (r["N"], r["instance"])))
        print(f"     {len(ok)} cores extracted "
              f"({sum(1 for r in ok if r['certified_minimal'])} certified minimal)")
        print(f"     {'instance':16} {'N':>3} {'core':>5} {'/pairs':>7} {'min':>5} "
              f"{'coin':>5} {'lab3':>5} {'cosets':>7}")
        for r in sorted(ok, key=lambda r: (r["N"], r["instance"])):
            print(f"     {r['instance']:16} {r['N']:3d} {r['core_size']:5d} "
                  f"{r['n_pairs_total']:7d} {str(r['certified_minimal']):>5} "
                  f"{str(r['coincident_pair_in_core']):>5} "
                  f"{str(r['label3_edges_in_core']):>5} {r['n_cosets_touched']:7d}")
        print(f"     wrote {os.path.relpath(out, ROOT)}")
    return dict(n=len(ok), rows=ok, out=out if ok else "")


