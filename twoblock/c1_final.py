ROW_ORDER = ["ord(d) even",
             "ord(d) odd, Theorem-1 obstructed",
             "ord(d) odd, not obstructed",
             "ord(d) even, Theorem-1 obstructed"]


def row_of(r) -> str:
    if r["ord_d_even"]:
        return ROW_ORDER[3] if r["theorem1_obstructed"] else ROW_ORDER[0]
    return ROW_ORDER[1] if r["theorem1_obstructed"] else ROW_ORDER[2]


def final_table(recs: list[dict]) -> dict:
    cols = ["SAT (solver)", "SAT (template witness)", "UNSAT", "UNDETERMINED"]
    tab: dict = defaultdict(Counter)
    for r in recs:
        if r["status"] == "SAT":
            c = cols[0]
        elif r["status_resolved"] == "SAT":
            c = cols[1]
        elif r["status_resolved"] == "UNSAT":
            c = cols[2]
        else:
            c = cols[3]
        tab[row_of(r)][c] += 1
    rows = [rr for rr in ROW_ORDER if tab[rr]]

    out = os.path.join(DATA, "c1_final.csv")
    with open(out, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["region"] + cols + ["total"])
        for rr in rows:
            w.writerow([rr] + [tab[rr][c] for c in cols] + [sum(tab[rr].values())])
        w.writerow(["total"] + [sum(tab[rr][c] for rr in rows) for c in cols]
                   + [sum(sum(tab[rr].values()) for rr in rows)])
    print(f"\n6.3  final contingency table -> {os.path.relpath(out, ROOT)}\n")
    hdr = f"  {'region':34} " + " ".join(f"{c:>22}" for c in cols) + f" {'total':>6}"
    print(hdr)
    print("  " + "-" * (len(hdr) - 2))
    for rr in rows:
        print(f"  {rr:34} " + " ".join(f"{tab[rr][c]:22d}" for c in cols)
              + f" {sum(tab[rr].values()):6d}")
    print(f"  {'total':34} "
          + " ".join(f"{sum(tab[rr][c] for rr in rows):22d}" for c in cols)
          + f" {sum(sum(tab[rr].values()) for rr in rows):6d}")

    esc = lambda s: s.replace("_", r"\_")
    lines = ["% requires: \\usepackage{booktabs,amsmath,amssymb}",
             "\\begin{table}[tb]", "\\centering", "\\small",
             "\\caption{Class-C1 instances at depth 6, by region. "
             "``SAT (template witness)'' counts instances whose solver run hit the time "
             "limit but for which an $\\varepsilon$-twisted invariant schedule was found "
             "and verified by $\\mathbb{F}_2$ simulation, which settles satisfiability "
             "constructively. UNDETERMINED instances are excluded from every separation "
             "statistic in this work.}",
             "\\label{tabS:c1}",
             "\\begin{tabular}{lrrrrr}", "\\toprule",
             "region & SAT (solver) & SAT (witness) & UNSAT & undet. & total \\\\",
             "\\midrule"]
    for rr in rows:
        lines.append(f"{esc(rr)} & " + " & ".join(str(tab[rr][c]) for c in cols)
                     + f" & {sum(tab[rr].values())} \\\\")
    lines.append("\\midrule")
    lines.append("total & " + " & ".join(str(sum(tab[rr][c] for rr in rows)) for c in cols)
                 + f" & {sum(sum(tab[rr].values()) for rr in rows)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              "\\\\[2pt]\\begin{minipage}{\\linewidth}\\footnotesize "
              "Solver time limit 600\\,s, single-threaded."
              "\\end{minipage}", "\\end{table}"]
    os.makedirs(TABLES, exist_ok=True)
    tp = os.path.join(TABLES, "tabS4_c1.tex")
    open(tp, "w").write("\n".join(lines) + "\n")
    print(f"  wrote {os.path.relpath(tp, ROOT)}")
    return dict(table={rr: dict(tab[rr]) for rr in rows}, csv=out, tex=tp)


