ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLES = os.path.join(ROOT, "tables")
DEPTH = 6


def v2(n: int) -> int:
    if n == 0:
        return 10 ** 9
    v = 0
    while n % 2 == 0:
        n //= 2
        v += 1
    return v


def _read(name: str) -> list[dict]:
    p = os.path.join(DATA, name)
    return list(csv.DictReader(open(p))) if os.path.exists(p) else []


def build_code(r) -> TwoBlockCode:
    return TwoBlockCode((int(r["N"]),), [tuple(a) for a in json.loads(r["A"])],
                        [tuple(b) for b in json.loads(r["B"])], r["instance"])


def load_all() -> list[dict]:
    """One record per class-C1 instance, joining every H4 output."""
    feats = {r["instance"]: r for r in _read("h4_features.csv")}
    sharp = {r["name"]: r for r in _read("h2_sharpness.csv") if r["class"] == "C1"}
    scan = _read("h4_mstar_scan.csv")
    tw2 = _read("h4_twisted.csv")

    found: dict[str, set] = defaultdict(set)
    unknown: dict[str, set] = defaultdict(set)
    tested: dict[str, set] = defaultdict(set)
    epsat: dict[str, dict] = {}
    for r in scan:
        m = int(r["m"])
        tested[r["instance"]].add(m)
        if r["exists"] == "True":
            found[r["instance"]].add(m)
            epsat.setdefault(r["instance"], {})[m] = r.get("eps_found", "")
        elif r["exists"] == "UNKNOWN":
            unknown[r["instance"]].add(m)
    for r in tw2:                                    # step 4 (m = 2) as a fallback
        if r["exists"] == "True":
            found[r["instance"]].add(2)
            tested[r["instance"]].add(2)

    out = []
    for name, f in feats.items():
        N = int(f["N"])
        ordd = int(f["ord_d"])
        d = json.loads(f["d"])[0] % N
        rec = dict(instance=name, N=N, A=f["A"], B=f["B"], status=sharp[name]["status"],
                   time_s=float(sharp[name]["time_s"]),
                   theorem1_obstructed=f["theorem1_obstructed"] == "True",
                   d=d, d_canon=json.loads(f["d_canon"])[0],
                   ord_d=ordd, ord_d_even=(ordd % 2 == 0),
                   v2_ord_d=v2(ordd), v2_d=v2(d) if d else 10 ** 9,
                   v2_N=v2(N), ord_delta0=int(f["ord_delta0"]),
                   d_in_2G=f["d_in_2G"] == "True",
                   n_components=int(f["n_components"]),
                   min_component_n=int(f["min_component_n"]),
                   twisted_ms=sorted(found[name]),
                   eps_found_at=epsat.get(name, {}),
                   unknown_ms=sorted(unknown[name]),
                   tested_ms=sorted(tested[name]),
                   twisted_verified=True,
                   smallest_m=(min(found[name]) if found[name] else None))
        out.append(rec)
    return sorted(out, key=lambda r: (r["N"], r["instance"]))


# ---------------------------------------------------------------- 6.1
def _M_even_at(rec: dict, m: int, eps_name: str) -> bool | None:
    """|M| parity for the eps that resolved this instance, M = <all six differences>."""
    from .encode import eps_value_m, homomorphisms_to_Zm
    from .templates import M_order
    code = build_code(rec)
    hs = [h for h in homomorphisms_to_Zm(code.G, m) if h["name"] == eps_name]
    if not hs:
        return None
    h = hs[0]
    ea = [eps_value_m(h["coeffs"], a, m) for a in code.A]
    eb = [eps_value_m(h["coeffs"], b, m) for b in code.B]
    return M_order(ea, eb, m) % 2 == 0


def resolve_timeouts(recs: list[dict]) -> dict:
    """TIMEOUT -> SAT when a verified twisted witness exists; else UNDETERMINED.

    The soundness assertion checks the **theorem** -- a twisted schedule requires
    |M| even, M generated by all six label differences -- and not ord(d), which is
    the refuted empirical fit.  ord(d) odd does not preclude a witness: |M| can be
    even while <eps(d)> has odd order.
    """
    bad_law, n_res = [], 0
    for r in recs:
        if r["status"] != "TIMEOUT":
            r["status_resolved"] = r["status"]
            r["resolved_by"] = ""
            continue
        if r["twisted_ms"]:
            r["status_resolved"] = "SAT"
            r["resolved_by"] = f"template-witness (m={r['smallest_m']})"
            n_res += 1
            m = r["smallest_m"]
            ev = _M_even_at(r, m, r.get("eps_found_at", {}).get(m, "")) \
                if r.get("eps_found_at") else None
            if ev is False:
                bad_law.append((r["instance"], m))
        else:
            r["status_resolved"] = "UNDETERMINED"
            r["resolved_by"] = ""
    if bad_law:
        raise AssertionError(
            "ABORT: a witness was found with |M| ODD, contradicting the theorem: "
            f"{bad_law}")
    n_to = sum(1 for r in recs if r["status"] == "TIMEOUT")
    n_und = sum(1 for r in recs if r["status_resolved"] == "UNDETERMINED")
    odd_res = [r["instance"] for r in recs
               if r["resolved_by"] and not r["ord_d_even"]]
    print(f"6.1  timeouts: {n_to};  resolved by verified template witness: {n_res};  "
          f"UNDETERMINED: {n_und}")
    print(f"     soundness assertion (no witness with |M| odd): PASS")
    if odd_res:
        print(f"     note: {len(odd_res)} of the resolved instances have ord(d) ODD "
              f"({odd_res[:5]}{' ...' if len(odd_res) > 5 else ''}).  This is expected: "
              f"the theorem constrains |M|, not ord(d); |M| is even for each of them.")
    return dict(n_timeout=n_to, n_resolved=n_res, n_undetermined=n_und,
                resolved_with_ord_d_odd=odd_res)


# ---------------------------------------------------------------- helper for C3
def minimal_period(rec: dict, depth: int = DEPTH, cap_seconds: float = 55.0):
    """Smallest m | N, 2 <= m < N, admitting a twisted schedule; None means m* = N."""
    import time as _t

    from .encode import find_twisted_invariant_schedule_Zm, homomorphisms_to_Zm
    code = build_code(rec)
    N = rec["N"]
    t0 = _t.time()
    for m in sorted(x for x in range(2, N) if N % x == 0):
        for h in homomorphisms_to_Zm(code.G, m):
            if _t.time() - t0 > cap_seconds:
                return "timeout"
            if find_twisted_invariant_schedule_Zm(code, depth, h["coeffs"], m):
                return m
    return None


