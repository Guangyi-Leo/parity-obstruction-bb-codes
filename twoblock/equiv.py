"""Equivalence of two-block codes: Aut(G), translations, and the block swap.

Two label sets define the same code up to relabelling of the qubits when

    (A, B) ~ (phi(A) + t1, phi(B) + t2)     phi in Aut(G), t1, t2 in G
    (A, B) ~ (B, A)

Translating A and B relabels the L- and R-qubits; an automorphism of G relabels
the group; the swap exchanges the two blocks.  Counting orbits under this
relation is what makes "N inequivalent instances" a defensible statement --
literal deduplication of sorted tuples does not.

Aut(G) is enumerated directly rather than by a formula: a homomorphism of
G = Z_{d_1} x ... x Z_{d_m} is fixed by the images of the m generators, subject
to d_i * phi(e_i) = 0, and is an automorphism exactly when those images
generate G.  For every group used in this paper (order at most 9) the candidate
set is a few hundred maps, so the enumeration is exact and instant.
"""
from __future__ import annotations

import itertools

_CACHE: dict[tuple, list] = {}


def _add(dims, g, h):
    return tuple((a + b) % d for a, b, d in zip(g, h, dims))


def _smul(dims, n, g):
    return tuple((n * a) % d for a, d in zip(g, dims))


def _elements(dims):
    return list(itertools.product(*(range(d) for d in dims)))


def _span(dims, vs):
    """The subgroup generated by `vs`."""
    seen = {tuple(0 for _ in dims)}
    frontier = list(seen)
    while frontier:
        nxt = []
        for g in frontier:
            for v in vs:
                h = _add(dims, g, v)
                if h not in seen:
                    seen.add(h)
                    nxt.append(h)
        frontier = nxt
    return seen


def automorphism_images(dims) -> list[tuple]:
    """Aut(G) as the tuple of generator images, one tuple per automorphism."""
    key = tuple(dims)
    if key in _CACHE:
        return _CACHE[key]
    els = _elements(dims)
    n = 1
    for d in dims:
        n *= d
    per_gen = [[v for v in els if _smul(dims, d, v) == tuple(0 for _ in dims)]
               for d in dims]
    out = []
    for cand in itertools.product(*per_gen):
        if len(_span(dims, cand)) == n:
            out.append(cand)
    _CACHE[key] = out
    return out


def automorphisms(dims) -> list:
    """Aut(G) as callables on element tuples."""
    def make(images):
        def phi(g):
            acc = tuple(0 for _ in dims)
            for gi, v in zip(g, images):
                acc = _add(dims, acc, _smul(dims, gi, v))
            return acc
        return phi
    return [make(im) for im in automorphism_images(dims)]


def canonical(dims, A, B, auts=None) -> tuple:
    """Lexicographically smallest representative of the orbit of (A, B).

    Only translations that put the identity into the set can matter, because
    every set here is normalised to contain 0; so t1 ranges over -phi(A) and t2
    over -phi(B) rather than over all of G.
    """
    dims = tuple(dims)
    auts = automorphisms(dims) if auts is None else auts
    A = [tuple(a) for a in A]
    B = [tuple(b) for b in B]

    def shifts(P):
        out = []
        for h in P:
            t = tuple((-u) % d for u, d in zip(h, dims))
            out.append(tuple(sorted(_add(dims, g, t) for g in P)))
        return out

    best = None
    for X, Y in ((A, B), (B, A)):
        for phi in auts:
            for sX in shifts([phi(g) for g in X]):
                for sY in shifts([phi(g) for g in Y]):
                    cand = (sX, sY)
                    if best is None or cand < best:
                        best = cand
    return best
