def consistency_checks(recs: list[dict], do_c3: bool = True) -> dict:  # noqa: ARG001
    res = {}
    print("\n6.2  consistency checks")

    # C1: every UNSAT not explained by Theorem 1 has ord(d) odd
    uns = [r for r in recs if r["status"] == "UNSAT"]
    unexp = [r for r in uns if not r["theorem1_obstructed"]]
    c1_bad = [r["instance"] for r in unexp if r["ord_d_even"]]
    print(f"  C1  UNSAT not explained by Theorem 1: {len(unexp)} of {len(uns)}; "
          f"of these {len(unexp)-len(c1_bad)} have ord(d) odd, {len(c1_bad)} do not "
          f"-> {'PASS' if not c1_bad else 'FAIL'}")
    if c1_bad:
        print(f"      exceptions: {c1_bad[:20]}")
    res["C1"] = dict(n_unsat=len(uns), n_unexplained=len(unexp),
                     exceptions=c1_bad, passed=not c1_bad)

    # C2: every SAT with ord(d) even admits a Z_{2^(v2(d)+1)}-twisted schedule
    sat_even = [r for r in recs
                if r["status_resolved"] == "SAT" and r["ord_d_even"]]
    c2_bad = []
    for r in sat_even:
        want = 2 ** (r["v2_d"] + 1)
        if want not in r["twisted_ms"]:
            c2_bad.append(dict(instance=r["instance"], N=r["N"], d=r["d"],
                               v2_d=r["v2_d"], want_m=want,
                               have=r["twisted_ms"],
                               reason=("m>12: no template/search at this m"
                                       if want > 12 else "unexpected")))
    print(f"  C2  SAT with ord(d) even: {len(sat_even)}; "
          f"admitting Z_(2^(v2(d)+1)): {len(sat_even)-len(c2_bad)}; "
          f"exceptions: {len(c2_bad)} -> {'PASS' if not c2_bad else 'see list'}")
    by_reason = Counter(x["reason"] for x in c2_bad)
    if c2_bad:
        print(f"      exception reasons: {dict(by_reason)}")
        for x in c2_bad[:12]:
            print(f"        {x['instance']:16} N={x['N']:>2} d={x['d']:>2} "
                  f"v2(d)={x['v2_d']} wanted m={x['want_m']} have={x['have']}")
        if len(c2_bad) > 12:
            print(f"        ... {len(c2_bad)-12} more (all in data/c1_final.csv)")
    res["C2"] = dict(n=len(sat_even), exceptions=c2_bad, passed=not c2_bad,
                     reasons=dict(by_reason))

    # C3: SAT with ord(d) odd -> minimal period m* = N.
    # m* is read from step 5a, which tested every EVEN m | N with 2 <= m < N; odd m
    # are excluded by the even-order criterion (a twisted schedule needs |M| even,
    # M = <eps(d)> <= Z_m, and every |M| is odd when m is odd).
    for r in recs:
        if r["twisted_ms"]:
            r["m_star"] = min(r["twisted_ms"])
            r["m_star_note"] = ""
        elif r["unknown_ms"]:
            r["m_star"] = "UNDETERMINED"
            r["m_star_note"] = ("m=" + ",".join(map(str, r["unknown_ms"]))
                                + " timed out at the cap")
        elif not r["tested_ms"] and all(r["N"] % k for k in range(2, r["N"])):
            r["m_star"] = r["N"]
            r["m_star_note"] = "N prime: no proper divisor exists"
        else:
            r["m_star"] = r["N"]
            r["m_star_note"] = "every proper divisor returned no schedule, uncapped"
    sat_odd = [r for r in recs if r["status_resolved"] == "SAT" and not r["ord_d_even"]]
    undet = [r["instance"] for r in sat_odd if r["m_star"] == "UNDETERMINED"]
    exc = [(r["instance"], r["N"], r["m_star"]) for r in sat_odd
           if r["m_star"] not in (r["N"], "UNDETERMINED")]
    print(f"  C3  SAT with ord(d) odd: {len(sat_odd)}; m* read from step 5a "
          f"(every even m | N tested, odd m excluded by the even-order criterion)")
    print(f"      m* = N for {len(sat_odd)-len(exc)-len(undet)} of {len(sat_odd)}; "
          f"{len(undet)} UNDETERMINED (a capped call, not an UNSAT); "
          f"{len(exc)} with a proper period -> {'PASS' if not exc else 'FAIL'}")
    if exc:
        print(f"      instances with a proper even period: {exc[:15]}")
    res["C3"] = dict(n=len(sat_odd), exceptions=exc, undetermined=undet,
                     passed=not exc)

    # the m* x v2(ord d) grid over every decided instance (step 5d view)
    grid = Counter()
    for r in recs:
        if r["status_resolved"] in ("SAT", "UNSAT"):
            grid[(r["m_star"] if r["twisted_ms"] else "N (none)", r["v2_ord_d"])] += 1
    print(f"\n      m* x v2(ord d) grid (decided instances):")
    v2s = sorted({k[1] for k in grid})
    hdr = f"      {'m*':>10} | " + " ".join(f"v2={v:<4}" for v in v2s)
    print(hdr)
    print("      " + "-" * (len(hdr) - 6))
    for ms in sorted({k[0] for k in grid}, key=lambda x: (isinstance(x, str), x)):
        print(f"      {str(ms):>10} | "
              + " ".join(f"{grid.get((ms, v), 0):<7d}" for v in v2s))
    res["C3"]["grid"] = {f"m*={k[0]},v2={k[1]}": v for k, v in sorted(grid.items(),
                                                                     key=str)}

    # C4: timeout distribution
    tos = [r for r in recs if r["status"] == "TIMEOUT"]
    grid = Counter((r["N"], "even" if r["ord_d_even"] else "odd",
                    r["theorem1_obstructed"]) for r in tos)
    print(f"\n  C4  TIMEOUT distribution ({len(tos)} instances)")
    print(f"      {'N':>4} {'ord(d)':>7} {'obstructed':>11} {'count':>6}")
    for kk in sorted(grid):
        print(f"      {kk[0]:4d} {kk[1]:>7} {str(kk[2]):>11} {grid[kk]:6d}")
    und = [r for r in recs if r["status_resolved"] == "UNDETERMINED"]
    off = [r["instance"] for r in und if r["ord_d_even"] or r["theorem1_obstructed"]]
    print(f"      UNDETERMINED: {len(und)}; all in the odd-ord(d), non-obstructed "
          f"region: {'YES' if not off else f'NO -- {len(off)} outside'}")
    if off:
        print(f"      outside: {off[:20]}")
    res["C4"] = dict(n_timeout=len(tos),
                     grid={f"N={k[0]},ord={k[1]},obstr={k[2]}": v
                           for k, v in sorted(grid.items())},
                     n_undetermined=len(und),
                     all_in_odd_nonobstructed=not off, outside=off)
    return res


