"""Step 6 -- finalise the class-C1 analysis.  Post-processing only.

No long solver runs: the only solving done here is the label-level twisted system
(a few hundred variables, milliseconds) and, optionally, bounded unsat-core
extraction with a hard per-instance limit.  Everything else reads
data/h2_sharpness.csv, data/h4_features.csv, data/h4_twisted*.csv, templates/ and
the step-5 outputs.
"""
