"""The coset identity for twisted schedules:  sum_{c in coset} (F_L(c)+F_R(c)) = |M| k l.

M is the subgroup of Z_m generated by the six label differences
alpha_s - alpha_s' and beta_t - beta_t'; the sum runs over the classes c of one coset
of M inside eps(G).

For a twisted schedule every X-check in class c carries the same label layers, so
F_L and F_R are functions of c alone and can be read straight off the label tables:

    F_L(c) = # { (s,t) : lay_Z^L[c + a_s + b_t][t] > lay_X^L[c][s] }
    F_R(c) = # { (t,s) : lay_Z^R[c + b_t + a_s][s] > lay_X^R[c][t] }

using (X_g, L_{g+a_s}) = s, (Z_g, L_{g-b_t}) = t, (X_g, R_{g+b_t}) = t,
(Z_g, R_{g-a_s}) = s from MODEL.md.  The same quantities are recomputed from the
expanded layering for every witness, as a cross-check on the formula.
"""
from __future__ import annotations

import csv
import json
import os
from math import gcd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
SCHED = os.path.join(ROOT, "schedules")
OUT = os.path.join(DATA, "twisted_identity.csv")
FIELDS = ["kind", "name", "m", "abs_M", "M_parity", "k", "l", "n_cosets", "coset",
          "lhs", "rhs", "equal"]


def subgroup_M(ea, eb, m: int) -> int:
    """|M| for M = <alpha_s - alpha_s', beta_t - beta_t'> <= Z_m."""
    g = m
    for v in list(ea) + list(eb):
        for w in list(ea) + list(eb):
            pass
    diffs = [a - b for i, a in enumerate(ea) for b in ea[i + 1:]]
    diffs += [a - b for i, a in enumerate(eb) for b in eb[i + 1:]]
    for d in diffs:
        g = gcd(g, d % m)
    g = gcd(g, m)
    return m // g if g else 1


def f_from_labels(labels, ea, eb, m, c):
    """(F_L(c), F_R(c)) from the twisted label tables."""
    XL, XR = labels[("X", "L")][c % m], labels[("X", "R")][c % m]
    FL = sum(1 for s in range(len(ea)) for t in range(len(eb))
             if labels[("Z", "L")][(c + ea[s] + eb[t]) % m][t] > XL[s])
    FR = sum(1 for t in range(len(eb)) for s in range(len(ea))
             if labels[("Z", "R")][(c + eb[t] + ea[s]) % m][s] > XR[t])
    return FL, FR


def cosets_of(M_size: int, image: list[int], m: int) -> list[list[int]]:
    """Cosets of M inside eps(G); M = (m/|M|) Z_m."""
    step = m // M_size                       # generator of M
    seen, out = set(), []
    for c in sorted(image):
        if c in seen:
            continue
        cos = sorted({(c + j * step) % m for j in range(M_size)} & set(image))
        for x in cos:
            seen.add(x)
        out.append(cos)
    return out


def check_labels(kind, name, labels, ea, eb, m, k, l, image=None) -> list[dict]:
    image = list(range(m)) if image is None else sorted(set(image))
    Ms = subgroup_M(ea, eb, m)
    rows = []
    for i, cos in enumerate(cosets_of(Ms, image, m)):
        lhs = sum(sum(f_from_labels(labels, ea, eb, m, c)) for c in cos)
        rhs = Ms * k * l
        rows.append(dict(kind=kind, name=name, m=m, abs_M=Ms,
                         M_parity="even" if Ms % 2 == 0 else "odd", k=k, l=l,
                         n_cosets=m // Ms, coset=i, lhs=lhs, rhs=rhs,
                         equal=lhs == rhs))
    return rows


def write(rows, path=None):
    with open(path or OUT, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader(); w.writerows(rows)
    return path or OUT
